"""Build the paper's displays from the split files (standard library only). Run from the example root:

    python analysis/make_displays.py table   # writes paper/tables/splits.tex
    python analysis/make_displays.py figure  # writes paper/figures/donors.tex (a TikZ bar chart)

Then record the build: steward paper displays --record
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPLITS = ["train", "validation", "test"]


def counts() -> list[tuple[str, int, int]]:
    rows = []
    for name in SPLITS:
        ids = [l.strip() for l in (ROOT / f"benchmarks/splits/{name}.txt").read_text().splitlines() if l.strip()]
        donors = {i.split("_")[0] for i in ids}
        rows.append((name.capitalize(), len(donors), len(ids)))
    return rows


def table() -> str:
    body = "\n".join(f"{n} & {d} & {s} \\\\" for n, d, s in counts())
    return ("% Generated by analysis/make_displays.py table; do not edit.\n"
            "\\begin{tabular}{lrr}\n\\toprule\nSplit & Donors & Samples \\\\\n\\midrule\n"
            f"{body}\n\\bottomrule\n\\end{{tabular}}\n")


def figure() -> str:
    bars = "\n".join(f"\\fill[gray!60] ({i * 1.2},0) rectangle ({i * 1.2 + 0.8},{d / 8:.3f});\n"
                     f"\\node[below] at ({i * 1.2 + 0.4},0) {{\\small {n}}};\n"
                     f"\\node[above] at ({i * 1.2 + 0.4},{d / 8:.3f}) {{\\small {d}}};"
                     for i, (n, d, _) in enumerate(counts()))
    return ("% Generated by analysis/make_displays.py figure; do not edit.\n"
            "\\begin{tikzpicture}\n" + bars + "\n\\end{tikzpicture}\n")


if __name__ == "__main__":
    kind = sys.argv[1] if len(sys.argv) > 1 else ""
    if kind == "table":
        (ROOT / "paper/tables/splits.tex").write_text(table(), newline="\n")
    elif kind == "figure":
        (ROOT / "paper/figures/donors.tex").write_text(figure(), newline="\n")
    else:
        sys.exit("usage: make_displays.py table|figure")
