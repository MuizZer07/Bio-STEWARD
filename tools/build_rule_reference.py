"""Generate the user guide's reference pages from the toolkit itself (0.10.0 U3): one source, never edited by hand.

    python tools/build_rule_reference.py           # write docs/reference/rules.md and commands.md
    python tools/build_rule_reference.py --check   # exit 1 when they are out of date (tests run this)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

HEADER = "<!-- generated by tools/build_rule_reference.py; do not edit -->\n"


def rules_page() -> str:
    from steward.cli import code_fixes
    from steward.report import NEXT
    from steward.rule_docs import RULE_DOCS
    from steward.rules import AREAS, RULES

    area_of = {r: a for a, rs in AREAS.items() for r in rs}
    out = [HEADER, "# Rule reference\n",
           "Every rule `steward check` evaluates, by area. `steward explain R-xx` prints the same text. A rule without "
           "its table in `steward.toml` is NOT_APPLICABLE, except R-01 and R-61, which always run.\n"]
    for area in sorted(AREAS):
        out.append(f"\n## {area}\n")
        for r in [x for x in sorted(RULES) if area_of.get(x) == area]:
            name, version = RULES[r]
            d = RULE_DOCS[r]
            out.append(f"\n### {r} `{name}`\n")
            out.append(f"*{d['scope']} governance · rule version {version}*\n")
            out.append(f"- **Checks:** {d['checks']}")
            out.append(f"- **Why:** {d['why']}")
            out.append(f"- **A PASS does not mean:** {d['not']}")
            out.append(f"- **Fix:** {NEXT.get(r, '-')}")
            fixes = code_fixes(r)  # S9 (0.14.0): each code with its own remedy, as `steward explain` prints it
            if fixes:
                out.append("- **Result codes:**")
                out += [f"  - `{c}`" + (f": {f}" if f else "") for c, f in fixes.items()]
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def commands_page() -> str:
    from steward.cli import build_parser

    parser = build_parser()
    sub = parser._subparsers._group_actions[0]  # noqa: SLF001
    out = [HEADER, "# Command reference\n", "Every `steward` command with its one-line purpose. `steward COMMAND --help` "
           "lists its options.\n", "| Command | Purpose |", "|---|---|"]
    helps = {a.dest: a.help for a in sub._choices_actions}  # noqa: SLF001
    for name in sorted(sub.choices):
        out.append(f"| `steward {name}` | {(helps.get(name) or '').replace('|', '/')} |")
    return "\n".join(out) + "\n"


NAMES = ("rules.md", "commands.md")


def _read_leaf(dfd: int, name: str) -> bytes | None:
    """The current page, read in the held directory and never through a link; None when absent. A link or a
    non-file is refused (0.10.0 review S8)."""
    import os
    import stat

    try:
        st = os.stat(name, dir_fd=dfd, follow_symlinks=False)
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(st.st_mode) or st.st_nlink > 1:
        raise RuntimeError(f"docs/reference/{name} is a link or not a regular file; remove it and build again")
    fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=dfd)
    with os.fdopen(fd, "rb") as f:
        return f.read()


def main(check: bool, root: Path = ROOT) -> int:
    """Every output goes through a descriptor of docs/reference walked without links from the repository root, and
    is replaced atomically in that directory; a linked folder or page is refused, in --check as well (S8)."""
    import os
    import secrets

    from steward.fsutil import LinkRefused, open_dir_beneath, open_at, write_all

    pages = {"rules.md": rules_page(), "commands.md": commands_page()}
    if check and not os.path.lexists(root / "docs" / "reference"):
        for n in NAMES:
            print(f"docs/reference/{n} is out of date; run python tools/build_rule_reference.py")
        return 1
    try:
        dfd = open_dir_beneath(root, ("docs", "reference"), create=not check)
    except LinkRefused as e:
        print(f"docs/reference cannot be opened without links: {e.strerror or e}", file=sys.stderr)
        return 2
    except FileNotFoundError:
        for n in NAMES:
            print(f"docs/reference/{n} is out of date; run python tools/build_rule_reference.py")
        return 1
    try:
        try:
            current = {n: _read_leaf(dfd, n) for n in NAMES}
        except RuntimeError as e:
            print(str(e), file=sys.stderr)
            return 2
        stale = [n for n in NAMES if current[n] != pages[n].encode("utf-8")]
        if check:
            for n in stale:
                print(f"docs/reference/{n} is out of date; run python tools/build_rule_reference.py")
            return 1 if stale else 0
        for n in stale:
            tmp = f".{n}.{secrets.token_hex(6)}.tmp"
            fd = open_at(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644, dfd)
            try:
                try:
                    write_all(fd, pages[n].encode("utf-8"))
                finally:
                    os.close(fd)
                os.replace(tmp, n, src_dir_fd=dfd, dst_dir_fd=dfd)
            except BaseException:
                try:
                    os.unlink(tmp, dir_fd=dfd)
                except OSError:
                    pass
                raise
        return 0
    finally:
        os.close(dfd)


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
