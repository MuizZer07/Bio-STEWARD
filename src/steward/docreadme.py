def _read(root: Path, cfg: StewardConfig, rel: str) -> bytes | None:
    path = docsite.source(root, cfg, rel)
    try:
        path.lstat()
    except FileNotFoundError:
        return None
    return records.read_rel(root, rel)


def _markers(data: bytes, *, appending: bool = False) -> tuple[int, int, bytes] | None:
    matches = []
    fence = b""
    offset = 0
    for line in data.splitlines(keepends=True):
        plain = line.rstrip(b"\r\n")
        match = FENCE.match(plain)
        if fence:  # a fence closes with the same character, at least as long, and nothing after it (CommonMark)
            if match and match[1][:1] == fence[:1] and len(match[1]) >= len(fence) and not match[2].strip():
                fence = b""
        elif match and not (match[1][:1] == b"`" and b"`" in match[2]):  # AF17: such a line opens no fence
            fence = match[1]
        elif plain in (START, END):
            matches.append((plain, offset, offset + len(line), line[len(plain):]))
        offset += len(line)
    if not matches:
        if fence and appending:
            raise docsite.DocsError("close the last code fence before adding the generated block")
        return None
    if [m[0] for m in matches] != [START, END]:
        raise docsite.DocsError("use one start marker followed by one end marker, each on its own line")
    start, end = matches
    return start[2], end[1], start[3]


def _gate(root: Path, cfg: StewardConfig) -> str:
    rel = cfg.docs.readme_report if cfg.docs else None
    data = _read(root, cfg, rel or DEFAULT_REPORT)
    if data is None:
        return "not recorded"
    try:
        report = Report.model_validate_json(data)
    except ValueError:
        raise docsite.DocsError("the saved check report is invalid") from None
    if report.verdict.repo_id != cfg.steward.repo_id:
        raise docsite.DocsError("the saved check report belongs to another project")
    gate = next((g for g in report.verdict.gates if g.name == "default"), None)
    if gate is None or not gate.evaluated:
        return "not evaluated"
    return "eligible" if gate.eligible else "blocked"


def _release(root: Path, cfg: StewardConfig) -> str:
    data = _read(root, cfg, (cfg.release or ReleaseSection()).manifest)
    if data is None:
        return "not recorded"
    try:
        manifest = json.loads(data)
        version = manifest.get("version") if isinstance(manifest, dict) else None
        if isinstance(manifest, dict) and version is None:
            return "not recorded"
        if not isinstance(version, str) or not version.strip() or not version.isprintable():
            raise ValueError
    except ValueError:
        raise docsite.DocsError("the release manifest has no usable version") from None
    return version


def _open_items(root: Path, cfg: StewardConfig) -> str:
    from .process import ID_LINE, STATUS_LINE, _status

    tc = cfg.tasks
    if tc is None:
        return "not configured"
    open_ids = set()
    for rel in matching_files(root, tc.specs):
        if rel == tc.board or any(glob_match(rel, pat) for pat in tc.archive):
            continue
        data = _read(root, cfg, rel)
        if data is None:
            continue
        text = data.decode("utf-8", errors="replace")
        id_match, status_match = ID_LINE.search(text), STATUS_LINE.search(text)
        status = _status(status_match[1] if status_match else None, tc.statuses)
        if id_match and re.fullmatch(tc.id_pattern, id_match[1]) and status in tc.statuses and status not in tc.closed:
            open_ids.add(id_match[1])
    return str(len(open_ids))


SVG_STYLE = """<style>
rect { fill: #eef1fb; stroke: #5b6585; }
text { fill: #1d2330; font: 600 13px system-ui, sans-serif; }
@media (prefers-color-scheme: dark) {
  rect { fill: #272e43; stroke: #a2add0; }
  text { fill: #f1f3ff; }
}
</style>
"""


def _svg(width: int, height: int, title: str, body: str) -> str:
    return (f'{SVG_MARKER}\n<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" role="img">\n<title>{escape(title)}</title>\n'
            f'{SVG_STYLE}{body}\n</svg>\n')


def _badge(text: str) -> str:
    width = 24 + len(text) * 8
    return _svg(width, 30, text, f'<rect x="0.5" y="0.5" width="{width - 1}" height="29" rx="6"/>\n'
                               f'<text x="{width / 2:g}" y="20" text-anchor="middle">{escape(text)}</text>')


def _lifecycle(title: str) -> str:
    content = []
    for index, step in enumerate(STEPS):
        x = 120 * index
        content.append(f'<rect x="{x + 0.5:g}" y="0.5" width="102" height="34" rx="6"/>')
        content.append(f'<text x="{x + 51}" y="22" text-anchor="middle">{step}</text>')
        if index < len(STEPS) - 1:
            content.append(f'<text x="{x + 105}" y="22">→</text>')
    return _svg(703, 35, title, "\n".join(content))


def render(root: Path, cfg: StewardConfig, *, pypi: bool = False) -> tuple[str, dict[str, str]]:
    """Render the block and images, then scan the bytes that will be published."""
    cards, study_paths = docsite.page_studies(root, cfg, strict=True)
    values = {
        "gate": ("Gate snapshot", _gate(root, cfg)),
        "release": ("Last release", _release(root, cfg)),
        "studies": ("Studies", str(len(study_paths))),
        "open-items": ("Open items", _open_items(root, cfg)),
    }
    docsite._raw_scan(root, cfg, "README badge values", [value for _, value in values.values()])
    lifecycle = " → ".join(STEPS)
    assets = {}
    if pypi:
        lines = ["| Record | Value |", "|---|---|"]
        lines += [f"| {label} | {records._md(value)} |" for label, value in values.values()]
        flow = lifecycle
    else:
        lines = []
        for name, (label, value) in values.items():
            rel = f"{ASSETS}/{name}.svg"
            text = f"{label}: {value}"
            lines.append(f"![{records._md(text)}]({rel})")
            assets[rel] = _badge(text)
        rel = f"{ASSETS}/lifecycle.svg"
        assets[rel] = _lifecycle(lifecycle)
        flow = f"![{lifecycle}]({rel})"
    configured = [label for field, label in CHECKS.items() if getattr(cfg, field)]
    lines += ["", "## What this project checks", "", f"Profile: **{cfg.steward.profile}**.", "",
              "- Project configuration and declared benchmark contracts",
              *(f"- {label}" for label in configured), "", "## Project lifecycle", "", flow, "",
              "The gate reports whether its required checks hold. The project owner decides whether to release.",
              "", "## Studies", "", cards.rstrip(), ""]
    block = "\n".join(lines)
    docsite._raw_scan(root, cfg, "README block", block)
    for path, svg in assets.items():
        docsite._raw_scan(root, cfg, path, svg)
    return block, assets


def _content(block: str, newline: bytes) -> bytes:
    return newline + block.encode().replace(b"\n", newline) + newline


def write(root: Path, cfg: StewardConfig) -> None:
    data = _read(root, cfg, README)
    original = data or b""
    span = _markers(original, appending=True)
    block, assets = render(root, cfg)
    if span:
        start, end, newline = span
        updated = original[:start] + _content(block, newline) + original[end:]
    else:
        newline = b"\r\n" if b"\r\n" in original else b"\n"
        separator = b"" if not original or original.endswith(newline * 2) else newline
        if original and not original.endswith(newline):
            separator += newline
        updated = original + separator + START + newline + _content(block, newline) + END + newline
    current = {rel: _read(root, cfg, rel) for rel in assets}
    for rel, raw in current.items():
        if raw is not None and not raw.startswith(SVG_MARKER.encode()):
            raise docsite.DocsError(f"move the existing {rel} before generating the README")
    for rel, svg in assets.items():
        if current[rel] != svg.encode():
            safe_write(root, rel, svg.encode(), exclusive=current[rel] is None)
    if updated != data:
        safe_write(root, README, updated, exclusive=data is None)


def check(root: Path, cfg: StewardConfig) -> tuple[Status, list[dict]] | None:
    """Check only the generated bytes. The project owns the surrounding prose."""
    assets_exist = (root / ASSETS).exists() or (root / ASSETS).is_symlink()
    # A linked README outside the feature's own output has no managed block we can inspect.
    if not assets_exist and (root / README).is_symlink():
        return None
    try:
        data = _read(root, cfg, README) or b""
        span = _markers(data)
        if not span:
            return (Status.INCOMPLETE, [{"code": "R-69.missing", "path": README}]) if assets_exist else None
        start, end, newline = span
        block, assets = render(root, cfg)
        current = {README: data[start:end], **{rel: _read(root, cfg, rel) for rel in assets}}
        expected = {README: _content(block, newline), **{rel: svg.encode() for rel, svg in assets.items()}}
        details = []
        for rel, raw in current.items():
            if raw is None:
                details.append({"code": "R-69.missing", "path": rel})
                continue
            docsite._raw_scan(root, cfg, rel, raw.decode("utf-8", errors="replace"))
            if raw != expected[rel]:
                details.append({"code": "R-69.stale", "path": rel})
        return (Status.INCOMPLETE if details else Status.PASS), details
    except docsite.PublicationError as e:
        return Status.FAIL, [{"code": "R-69.private", "path": README, "message": str(e)}]
    except (docsite.DocsError, OSError) as e:
        return Status.FAIL, [{"code": "R-69.readme_invalid", "path": README, "message": str(e)}]
