def init(root: Path, code: str) -> list[str]:
    import os

    from .fsutil import LinkRefused, open_dir_beneath

    made = []
    guard(root)  # review O5: init writes through the same guard as every other command
    for sub in SUBDIRS:
        guard(root, sub)
        existed = (folder(root) / sub).is_dir()
        try:
            os.close(open_dir_beneath(root, (FOLDER, sub), create=True))  # 0.9.0 A6: made by descriptor
        except LinkRefused as e:
            raise BoundaryError(f"{FOLDER}/{sub}: {e.strerror or e}") from None
        if not existed:
            forget(write_new(root, sub, ".keep", b""))  # no state to record: release the held directory now
            made.append(f"{FOLDER}/{sub}/")
    guard(root, "README.md")
    if not (folder(root) / "README.md").is_file():
        _write_top(root, "README.md", (README.format(code=code) + state_tables()).encode("utf-8"))
        made.append(f"{FOLDER}/README.md")
    return made


def _write_top(root: Path, name: str, data: bytes) -> None:
    import os

    from .fsutil import LinkRefused, open_at, open_dir_beneath

    try:
        dfd = open_dir_beneath(root, (FOLDER,))
    except LinkRefused as e:
        raise BoundaryError(f"{FOLDER}: {e.strerror or e}") from None
    try:
        fd = open_at(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644, dfd)
        try:
            os.write(fd, data)
        finally:
            os.close(fd)
    finally:
        os.close(dfd)


