def peer_ids_seen(root: Path, peer: str) -> set[str] | None:
    """AH2: the item IDs a URL peer's ledger held at the last pull (a local record), or None when never recorded."""
    import json

    from .records import RecordRefused, read_rel

    try:
        doc = json.loads(read_rel(root, SEEN).decode("utf-8"))
    except (RecordRefused, ValueError):
        return None
    ids = doc.get(peer) if isinstance(doc, dict) else None
    if ids is None or (isinstance(ids, dict) and set(ids) == {"unverified"}):  # AK4: kept, but not evidence now
        return None
    if not isinstance(ids, list) or not all(isinstance(i, str) and valid_id(i) for i in ids):  # AI2
        raise ValueError(f"{SEEN} holds an entry for {peer} that is not a list of item IDs: run steward exchange pull "
                         f"{peer} to record it again")
    return set(ids)


def forget_peer_ids(root: Path, peer: str) -> None:
    """AH2, AK4: mark a peer's record unverified, so numbering refuses until a pull verifies its ledger again; the IDs
    it held are kept and merged back then, so no reservation is lost."""
    import json

    from .fsutil import safe_write
    from .records import RecordRefused, read_rel

    try:
        doc = json.loads(read_rel(root, SEEN).decode("utf-8"))
    except (RecordRefused, ValueError):
        return
    if isinstance(doc, dict) and isinstance(doc.get(peer), list):
        doc[peer] = {"unverified": doc[peer]}
        safe_write(root, SEEN, (json.dumps(doc, indent=1, sort_keys=True) + "\n").encode())


def record_peer_ids(root: Path, peer: str, ids: set[str]) -> None:
    import json

    from .fsutil import safe_write
    from .records import RecordRefused, read_rel

    try:
        doc = json.loads(read_rel(root, SEEN).decode("utf-8"))
        doc = doc if isinstance(doc, dict) else {}
    except (RecordRefused, ValueError):
        doc = {}
    old = doc.get(peer, [])
    old = old.get("unverified", []) if isinstance(old, dict) else old  # AK4: earlier reservations come back
    keep = {i for i in old if isinstance(i, str) and valid_id(i)} if isinstance(old, list) else set()  # AI2
    doc[peer] = sorted(keep | ids)
    safe_write(root, SEEN, (json.dumps(doc, indent=1, sort_keys=True) + "\n").encode())


def _state_history(entries: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    history: dict[str, list[dict[str, Any]]] = {}
    for entry in entries:
        if entry.get("kind") == "state" and valid_id(entry.get("item")):
            history.setdefault(entry["item"], []).append(entry)
    return history


def _verified_history(data: bytes) -> dict[str, list[dict[str, Any]]] | None:
    from .ledger import verify_bytes

    try:
        checked = verify_bytes(data)
    except (ValueError, RecursionError):
        return None
    return None if checked.errors or checked.torn_tail else _state_history(checked.entries)


def peer_history(path: Path, sha: str) -> dict[str, list[dict[str, Any]]] | None:
    """States in the receiver's committed ledger, or None if it could not be verified."""
    from .fsutil import git_run

    rel = f"{FOLDER}/log.jsonl"
    tree = git_run(path, "ls-tree", sha, "--", rel, timeout=10)
    if tree.returncode:
        return None
    if not tree.stdout:
        return {}
    if not tree.stdout.startswith((b"100644 blob ", b"100755 blob ")):
        return None
    ledger_blob = git_run(path, "show", f"{sha}:{rel}", timeout=10)
    if ledger_blob.returncode != 0:
        return None
    # AF13: the ledger must be that receiver's own exchange ledger: its genesis names the exchange ledger and the
    # repo_id the receiver's steward.toml declares at the same commit
    import json as _json

    try:
        first = _json.loads(ledger_blob.stdout.split(b"\n", 1)[0])
        cfg = git_run(path, "show", f"{sha}:steward.toml", timeout=10)
        st = tomllib.loads(cfg.stdout.decode("utf-8")).get("steward") if cfg.returncode == 0 else None
        rid = st.get("repo_id") if isinstance(st, dict) else None  # AG4: a malformed section is unchecked
    except (ValueError, UnicodeDecodeError, RecursionError, AttributeError, TypeError):
        return None
    if not isinstance(first, dict) or first.get("kind") != "genesis" or first.get("ledger") != "exchange" \
            or not rid or first.get("repo_id") != rid:
        return None
    return _verified_history(ledger_blob.stdout)


def recorded_receipt(entries: list[dict[str, Any]]) -> str | None:
    """A receipt hash or an acknowledgement from before receipts carried hashes."""
    if not entries or entries[0].get("state") != "acknowledged":
        return None
    return "unhashed" if "received" not in entries[0] else receipt_sha(entries)


def peer_outbox(path: Path, sha: str, sub: str = "outbox") -> list[tuple[str, bytes]]:
    """(file name, bytes) of every Markdown file in the peer's committed outbox (or responses/)."""
    from .fsutil import git_run

    if git_run(path, "cat-file", "-e", f"{sha}:{FOLDER}/{sub}").returncode != 0:
        return []
    out = git_run(path, "ls-tree", "-z", f"{sha}:{FOLDER}/{sub}", timeout=30)
    if out.returncode != 0:
        raise PeerError(f"cannot list the peer's {sub}/")
    found = []
    for rec in out.stdout.split(b"\0"):
        if not rec:
            continue
        meta, name = rec.split(b"\t", 1)
        mode, kind, obj = meta.split()
        fname = name.decode("utf-8", errors="replace")
        if kind != b"blob" or mode not in (b"100644", b"100755") or not fname.endswith(".md") or "/" in fname:
            continue
        blob = git_run(path, "cat-file", "blob", obj.decode(), timeout=30)
        if blob.returncode:
            raise PeerError(f"cannot read a file in the peer's {sub}/")
        if len(blob.stdout) <= 1 << 20:
            found.append((fname, blob.stdout))
    return sorted(found)


def _delivery_item(name: str, data: bytes) -> Item | None:
    try:
        item = Item.model_validate(parse(data.decode("utf-8"))[0])
    except (ValueError, RecursionError):
        return None
    return item if name == f"{item.id}.md" and b"\x00" not in data else None


def _addressed_items(path: Path, sha: str, sender: str, receiver: str) -> Iterator[tuple[Item, bytes]]:
    for sub in ("outbox", "responses"):
        for name, data in peer_outbox(path, sha, sub):
            item = _delivery_item(name, data)
            if item and item.from_ == sender and item.to == receiver:
                yield item, data


def discover_peers(root: Path, config: ExchangeSection,
                   recipients: Collection[str] = ()) -> tuple[dict[str, str | ExchangePeer], set[str]]:
    """Add registered recipients and checkouts whose committed configuration or items address this project."""
    from .cleanup import registered

    peers = dict(config.peers)
    if os.environ.get("STEWARD_NO_REGISTRY"):
        return peers, set()
    found: dict[str, set[Path]] = {}
    for entry in registered():
        try:
            path = entry.resolve()
            if path == root.resolve():
                continue
            sha = _checkout_head(path, "HEAD")
            exchange = _committed_exchange(path, sha)
            name = exchange.code
            if name == config.code or name in peers:
                continue
            if name in recipients or config.code in exchange.peers or next(_addressed_items(path, sha, name, config.code), None):
                found.setdefault(name, set()).add(path)
        except (PeerError, OSError, subprocess.TimeoutExpired, RuntimeError):
            continue
    ambiguous = {name for name, paths in found.items() if len(paths) > 1}
    for name, paths in found.items():
        if name not in ambiguous:
            peers[name] = str(next(iter(paths)))
    return peers, ambiguous


@dataclass
class Delivery:
    item: Item
    state: Literal["waiting", "received", "unchecked", "changed"]


@dataclass
class DeliveryStatus:
    incoming: list[Delivery] = field(default_factory=list)
    outgoing: list[Delivery] = field(default_factory=list)
    unavailable: set[str] = field(default_factory=set)


def _delivery(item: Item, data: bytes, history: dict[str, list[dict[str, Any]]] | None) -> Delivery:
    if history is None:
        return Delivery(item, "unchecked")
    receipt = recorded_receipt(history.get(item.id, []))
    if receipt is None:
        return Delivery(item, "waiting")
    return Delivery(item, "received" if receipt in ("unhashed", hashlib.sha256(data).hexdigest()) else "changed")


def delivery_status(root: Path, config: ExchangeSection, *, overdue_only: bool = False,
                    network: bool = False) -> DeliveryStatus:
    """Compare the items each project sends with the receiver's ledger. A peer declared by URL is fetched only with
    `network` (exchange pull, exchange status --fetch); otherwise its items stay unchecked (AF6)."""
    outgoing: dict[str, list[tuple[Item, bytes]]] = {}
    today = date.today()
    for sub in ("outbox",) if overdue_only else ("outbox", "responses"):
        try:
            files = sorted(guard(root, sub).glob("*.md"))
        except (BoundaryError, OSError):
            continue
        for path in files:
            try:
                data = guard(root, sub, path.name).read_bytes()
            except (BoundaryError, OSError):
                continue
            item = _delivery_item(path.name, data)
            if item and item.from_ == config.code and item.to != config.code:
                if not overdue_only or (today - item.filed).days > config.delivery_days:
                    outgoing.setdefault(item.to, []).append((item, data))
    status = DeliveryStatus()
    if overdue_only and not outgoing:
        return status
    peers, status.unavailable = discover_peers(root, config, outgoing.keys())
    if not overdue_only:
        try:
            ledger_path = guard(root, "log.jsonl")
            local = _verified_history(ledger_path.read_bytes()) if ledger_path.is_file() else {}
        except (BoundaryError, OSError):
            local = None
    for name in sorted(outgoing if overdue_only else peers.keys() | outgoing.keys()):
        history = None
        if name in peers and not network and _peer_source(peers[name])[2]:
            status.unavailable.add(name)
        elif name in peers:
            try:
                with peer_revision(root, name, peers[name]) as (path, sha):
                    if not overdue_only:
                        status.incoming.extend(_delivery(item, data, local)
                                               for item, data in _addressed_items(path, sha, name, config.code))
                    if name in outgoing:
                        history = peer_history(path, sha)
            except PeerError:
                status.unavailable.add(name)
        status.outgoing.extend(_delivery(item, data, history) for item, data in outgoing.get(name, []))
    return status


def delivery_advice(delivery: Delivery, days: int, item_id: str, peer: str) -> str | None:
    if delivery.state == "received" or delivery.item.kind == "response" or (date.today() - delivery.item.filed).days <= days:
        return None
    extra = {"unchecked": " (receiver's ledger could not be checked)",
             "changed": " (receipt covers different bytes)"}.get(delivery.state, "")
    return f"{item_id} to {peer} has no delivery receipt after more than {days} days{extra}"


class ItemSkipped(ValueError):
    """One incoming item is not taken; a pull reports it and goes on with the others."""


class TermsRefused(ItemSkipped):
    """An incoming item hits this project's own R-07 term lists or local-path check (FB-018): it is not received,
    so a non-compliant item never enters the ledger. `hits` names the lines (never a private list's term)."""

    def __init__(self, item_id: str, hits: list[dict[str, Any]]):
        self.item_id, self.hits = item_id, hits  # item_id is already redacted by the caller when it hits a list (AB4)
        where = "; ".join(f"line {h['line']}: {h['what']}" for h in hits[:10]) + (" …" if len(hits) > 10 else "")
        super().__init__(f"{item_id} is not received: it hits this project's term lists ({where}). Ask the sender to "
                         "re-file it in generic words, or receive it anyway with --allow-terms")


def receive(root: Path, repo_id: str, code: str, data: bytes, source: dict[str, Any],
            screen: Any = None) -> tuple[str, str]:
    """Take one item into inbox/: (id, outcome) with outcome received | already received | changed at the peer.
    The file and its acknowledgement (with the sender's commit and the file's hash) are recorded together. `screen`,
    when given, is called as screen(rel, data) before a new item is written and returns its term hits; any hit
    refuses the receipt with TermsRefused (FB-018)."""
    import hashlib

    head, _ = parse(data.decode("utf-8"))
    it = Item.model_validate(head)
    if it.to != code or it.from_ == code:
        raise ValueError(f"{it.id} is addressed to {it.to} from {it.from_}; this project is {code}")
    peer = source.get("from")
    if peer not in (None, "file") and it.from_ != peer:  # Q11: an item pulled from a peer is that peer's own
        raise ValueError(f"{it.id} claims sender {it.from_}, but it came from peer {peer}")
    target = None
    if it.kind == "response" and it.responds_to:
        tp = folder(root) / "outbox" / f"{it.responds_to}.md"
        if tp.is_file():
            target = Item.model_validate(parse(tp.read_text(encoding="utf-8"))[0])
            if target.to != it.from_:  # Q11: only the project the item was sent to may answer it
                raise ValueError(f"{it.id} answers {it.responds_to}, which was addressed to {target.to}, not {it.from_}")
    if b"\x00" in data:  # AB8: R-07 would skip it as binary and check nothing; stricter than R-07, on purpose
        raise ItemSkipped(f"{shown(it.id, screen)} is not received: it holds a NUL byte, so it cannot be checked as text")
    hist = states(root).get(it.id, [])
    if not (folder(root) / "inbox" / f"{it.id}.md").is_file() and hist:
        if may_be_gone(root, it.id):  # FB-018: decided here and its file removed; never received again
            st = next(e["state"] for e in reversed(hist) if e.get("state") in RETIRED_STATES)
            return it.id, f"already received; {st} here"
        raise ItemSkipped(f"{shown(it.id, screen)}: the ledger records it but exchange/inbox/{shown(it.id, screen)}.md is "
                          "missing; restore it from git (an inbox item is never received twice)")

    def refuse_on_terms() -> None:
        if screen is not None:
            hits = screen(f"{FOLDER}/inbox/{it.id}.md", data)
            if hits:
                raise TermsRefused(shown(it.id, screen), hits)
    existing = folder(root) / "inbox" / f"{it.id}.md"
    if existing.is_file():
        same = existing.read_bytes() == data
        if same and not hist:
            refuse_on_terms()  # AB3: a receipt recovered for left-behind bytes passes the same screen
        rec = next((e.get("received") for e in states(root).get(it.id, []) if isinstance(e.get("received"), dict)), None)
        if same and not states(root).get(it.id):  # R7 (0.12.0): a file left without any state (an interrupted
            ledger_ok(root)                        # receive) gets its receipt now, never "already received" alone
            set_state(root, repo_id, it.id, "acknowledged", f"received from {it.from_}", code, False, it.kind,
                      {"received": {**source, "sha256": hashlib.sha256(data).hexdigest()}}, place="inbox")
            rec = {"sha256": hashlib.sha256(data).hexdigest()}
        intact = same and isinstance(rec, dict) and rec.get("sha256") == hashlib.sha256(data).hexdigest()
        if intact and it.kind == "release":  # U7: a retry completes the observations, after the receipt is checked
            _observe_shipped(root, repo_id, it, data)
        if intact and target is not None and not target_mismatch(root, data.decode("utf-8", "replace"), it.responds_to):
            observe(root, repo_id, it.responds_to, decided_state(data.decode("utf-8")), it.from_, it.id)  # Q10, R7
        return it.id, "already received" if same else "changed at the peer"
    refuse_on_terms()
    ledger_ok(root)
    dest = write_new(root, "inbox", f"{it.id}.md", data)
    try:
        set_state(root, repo_id, it.id, "acknowledged", f"received from {it.from_}", code, False, it.kind,
                  {"received": {**source, "sha256": hashlib.sha256(data).hexdigest()}}, place="inbox")
    except Exception:
        if not keep_if_appended(root, dest, it.id, 0, "acknowledged",  # U5 (0.17.0): exactly this receipt
                                received={**source, "sha256": hashlib.sha256(data).hexdigest()}):
            rollback(root, dest)
        raise
    else:
        forget(dest)
    if it.kind == "release":  # DEF-028: the notice names this project's items the release shipped
        _observe_shipped(root, repo_id, it, data)
    if target is not None and target_mismatch(root, data.decode("utf-8", "replace"), it.responds_to):
        return it.id, "received; it answers other bytes than this project's own item of that ID (an ID collision): " \
                      "its decision is not recorded against the item"
    if target is not None:
        observe(root, repo_id, it.responds_to, decided_state(data.decode("utf-8")), it.from_, it.id)
    return it.id, "received"


def shown(item_id: str, screen: Any) -> str:
    """The item ID as it may be printed: withheld when it matches one of this project's private terms (AB4)."""
    hides = getattr(screen, "hides", None)
    return "an incoming item (its ID matches a private term)" if hides is not None and hides(item_id) else item_id


ANSWERS = re.compile(r"^## Answers\s*\n+(\S+) sha256:([0-9a-f]{64})\s*$", re.M)


def answered(text: str) -> tuple[str, str] | None:
    """(item ID, sha256 of the item as the responder received it), from a response's `## Answers` section
    (0.12.0, FB-017); None for a response written before 0.12.0."""
    m = ANSWERS.search(text)
    return (m.group(1), m.group(2)) if m else None


def target_mismatch(root: Path, text: str, item_id: str) -> bool:
    """A response names a hash for the item it answers, and this project's own item of that ID has other bytes: an
    ID collision, not an answer to this item (FB-017)."""
    if not valid_id(item_id):
        return True  # U4: never a path from an unchecked ID
    if re.search(r"^## Answers\s*$", text, re.M) and answered(text) is None:
        return True  # U8 (0.12.0): a present but malformed binding is never read as "no binding"
    a = answered(text)
    if a is not None and a[0] != item_id:
        return True  # U8: the binding names another item
    tp = folder(root) / "outbox" / f"{item_id}.md"
    return bool(a and tp.is_file() and hashlib.sha256(tp.read_bytes()).hexdigest() != a[1])


NOT_DELIVERED = re.compile(r"known issues?|deferred|declined|not (?:in|shipped)|planned|later", re.I)


def delivered_ids(section: str, candidates: set[str]) -> list[str]:
    """The item IDs a changelog section names as delivered: under any subheading except known issues, deferred,
    declined or planned work (DEF-028)."""
    out: list[str] = []
    delivered = True
    fence: str | None = None
    for line in section.splitlines():
        m = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", line)
        if m:  # U7 (0.15.0): a fence closes with the same character, at least as long, and nothing after it
            if fence is None:
                if not (m.group(1)[0] == "`" and "`" in m.group(2)):  # 0.17.0: a backtick opener's info has no backtick
                    fence = m.group(1)
                    continue
            elif m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and not m.group(2).strip():
                fence = None
                continue
        if fence or re.match(r"^( {4,}|\t)", line):  # X6 (0.15.0): indented code is an example too
            continue
        h = re.match(r"^#{2,5}\s+(.*)", line)
        if h:
            delivered = not NOT_DELIVERED.search(h.group(1))
            continue
        if delivered:
            out += [i for i in re.findall(r"(?<![\w-])[A-Z]{2,6}-[A-Z]+-\d+(?![\w-])", line) if i in candidates]
    return sorted(set(out))


SHIPPED_SECTION = re.compile(r"^## Shipped items\s*\n+((?:- \S+\s*\n?)+)", re.M)


def _version(text: str) -> tuple[int, ...] | None:
    m = re.fullmatch(r"v?(\d+(?:\.\d+){0,3})", text)
    return tuple(int(x) for x in m.group(1).split(".")) if m else None


def released_since(root: Path, note: str | None) -> str | None:
    """The newest release tag at or after the version a `deferred` note names (`v0.8.2`, `deferred: v0.8.2 …`), or
    None. A version that was never tagged (folded into a later release) is passed once a later one is (DEF-028)."""
    from .fsutil import git_run

    m = re.search(r"(?<![\w.])v?\d+(?:\.\d+){1,3}(?![\w.])", note or "")
    target = _version(m.group()) if m else None
    if target is None:
        return None
    out = git_run(root, "tag", "--list", "v*", text=True, timeout=10)
    tags = [(v, t) for t in out.stdout.split() if (v := _version(t)) is not None] if out.returncode == 0 else []
    later = [t for v, t in sorted(tags) if v >= target]
    return later[-1] if later else None


def _observe_shipped(root: Path, repo_id: str, it: "Item", data: bytes) -> None:
    """Record, once each, that the sender's release shipped this project's items: only items this project sent to that
    sender (U7)."""
    own = folder(root) / "outbox"
    for item in shipped_in_notice(data.decode("utf-8", "replace")):
        p = own / f"{item}.md"
        if not p.is_file() or p.is_symlink():
            continue
        try:
            head = parse(p.read_text(encoding="utf-8"))[0]
        except (ValueError, UnicodeDecodeError, RecursionError):
            continue
        if head.get("from") == it.to and head.get("to") == it.from_:
            observe(root, repo_id, item, "shipped", it.from_, it.id)


def shipped_in_notice(text: str) -> list[str]:
    m = SHIPPED_SECTION.search(text)
    return [i for i in re.findall(r"^- (\S+)", m.group(1), re.M) if valid_id(i)] if m else []  # U4


def decided_state(text: str) -> str:
    """The state a response reports, from its `## Decision` section (`STATE: note`), or `responded`."""
    m = re.search(r"^## Decision\s*\n+([a-z-]+):", text, re.M)
    states = {s for v in TWO_WAY.values() for s in v}
    return m.group(1) if m and m.group(1) in states else "responded"


class _Recorded(Exception):
    pass


def observe(root: Path, repo_id: str, item_id: str, state: str, by: str, evidence: str) -> dict[str, Any] | None:
    """Record what the receiver reported about this project's own item, as an observation with its source: never as
    this project's own state (DEF-025; principle 3). Checked and appended under the ledger lock, so two retries
    cannot both add it (R7)."""
    def decide(entries: list[dict[str, Any]]) -> tuple[str, dict[str, Any]]:
        if any(e.get("kind") == "observed" and e.get("item") == item_id and e.get("evidence") == evidence for e in entries):
            raise _Recorded()
        return "observed", {"item": item_id, "state": state, "by": by, "evidence": evidence}
    try:
        return ledger(root, repo_id).transaction(decide)
    except _Recorded:
        return None


# FB-019 (0.18.0): how far along its lifecycle an observed state is. A notice's `shipped` and a response's
# `accepted` can arrive in one pull in either order; status shows the furthest, never only the last written. A final
# decision (declined, merged, closed and the like) ends the lifecycle and outranks every earlier stage.
STAGE = {"responded": 0, "noted": 0, "acknowledged": 1, "verified": 2, "not-reproduced": 2, "accepted": 3,
         "deferred": 3, "shipped": 4, "adopted": 5, "declined": 6, "merged": 6, "superseded": 6, "withdrawn": 6,
         "closed": 6}


def furthest(obs: list[dict[str, Any]]) -> dict[str, Any] | None:
    """The observation furthest along the lifecycle; the later one on a tie (a re-decision at the same stage)."""
    best = None
    for o in obs:
        if best is None or STAGE.get(o.get("state", ""), 0) >= STAGE.get(best.get("state", ""), 0):
            best = o
    return best


def observations(root: Path) -> dict[str, list[dict[str, Any]]]:
    from .ledger import verify

    out: dict[str, list[dict[str, Any]]] = {}
    p = folder(root) / "log.jsonl"
    for e in verify(p).entries if p.is_file() else []:
        if e.get("kind") == "observed":
            out.setdefault(e["item"], []).append(e)
    return out


