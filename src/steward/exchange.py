def changelog_section(text: str, version: str) -> str | None:
    """The CHANGELOG section whose level-2 heading names this version (`## 1.2.0 …` or `## v1.2.0 …`)."""
    lines = text.splitlines()
    pat = re.compile(rf"^##\s+\[?v?{re.escape(version)}\]?(\s|$|\()")
    start = next((i for i, l in enumerate(lines) if pat.match(l)), None)
    if start is None:
        return None
    end = next((j for j in range(start + 1, len(lines)) if re.match(r"^##\s", lines[j])), len(lines))
    return "\n".join(lines[start:end]).strip() + "\n"


def version_key(v: str) -> tuple[int, ...] | None:
    m = re.match(r"^v?(\d+(?:\.\d+)*)", v)
    return tuple(int(x) for x in m.group(1).split(".")) if m else None
