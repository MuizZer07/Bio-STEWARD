def state_tables() -> str:
    """The state machines, as tables generated from the code (FB-016): the README never disagrees with them."""
    out = ["\n## States\n", "Every change is one line in `log.jsonl`. A state marked * needs `--note` (a version, a reason, "
           "a target ID or evidence); a received item's `shipped` note starts with this project's release tag.\n"]
    for title, m in (("Items received (inbox): the receiver decides", TWO_WAY),
                     ("This project's own items (outbox): the receiver's states arrive as observations", REQUESTER),
                     ("Responses received (inbox): a decision already, noted on receipt", RESPONSE),
                     ("Release notices: the consumer acknowledges, then adopts or declines", RELEASE),
                     ("One-way items (oneway/)", ONE_WAY)):
        out += [f"\n### {title}\n", "| From | To |", "|---|---|"]
        for frm, tos in m.items():
            if tos:
                out.append(f"| {frm or '(new)'} | " + ", ".join(t + ("*" if t in NEEDS_NOTE else "") for t in sorted(tos)) + " |")
    return "\n".join(out) + "\n"


def items(root: Path) -> dict[str, list[tuple[str, str]]]:
    """place -> [(rel path, text)]."""
    out: dict[str, list[tuple[str, str]]] = {}
    for sub in SUBDIRS:
        d = folder(root) / sub
        # a file that is not UTF-8 is still listed (and reported invalid by R-53), never a crash (0.10.0 H2)
        out[sub] = [(p.relative_to(root).as_posix(), p.read_text(encoding="utf-8", errors="replace"))
                    for p in sorted(d.glob("*.md"))] if d.is_dir() else []
    return out


def states(root: Path) -> dict[str, list[dict[str, Any]]]:
    """ID -> its ledger entries, in order."""
    from .ledger import verify

    out: dict[str, list[dict[str, Any]]] = {}
    p = folder(root) / "log.jsonl"
    if not p.is_file():
        return out
    for e in verify(p).entries:
        if e.get("kind") == "state":
            out.setdefault(e["item"], []).append(e)
    return out


def current(entries: list[dict[str, Any]]) -> str | None:
    return entries[-1]["state"] if entries else None


def next_id(root: Path, code: str, kind: str, peers: dict[str, str | ExchangePeer] | None = None) -> str:
    """The next unused number, including IDs already recorded in a peer's committed ledger."""
    found = set()
    for peer, source in (peers or {}).items():
        if _peer_source(source)[2]:  # AF6, AH2: never fetched here; the IDs recorded at the last pull count
            seen = peer_ids_seen(root, peer)
            if seen is None:
                raise ValueError(f"{peer} is a URL peer with no recorded IDs: run steward exchange pull {peer} first, so "
                                 "a number it holds is never issued again")
            found.update(seen)
            continue
        try:
            with peer_revision(root, peer, source) as (path, sha):
                history = peer_history(path, sha)
                found.update(history or {})
        except PeerError:
            continue
    prefix = f"{code}-{KINDS[kind]}-"
    names = [Path(rel).stem for place in items(root).values() for rel, _ in place] + list(states(root)) \
        + sorted(found)
    used = [int(m.group(3)) for n in names for m in [ID.match(n)] if m and n.startswith(prefix)]
    return f"{prefix}{(max(used) + 1 if used else 1):03d}"


def machine_for(place: str, kind: str | None) -> dict[str | None, set[str]]:
    if place == "oneway":
        return ONE_WAY
    if kind == "release":
        return RELEASE
    if kind == "response" and place == "inbox":
        return RESPONSE
    return REQUESTER if place == "outbox" else TWO_WAY


def file_outbox(root: Path, repo_id: str, item: Item, data: bytes) -> Path:
    """Write an outgoing item and its filed state, recovering the file if the state was never appended."""
    ledger_ok(root)
    path = write_new(root, "outbox", f"{item.id}.md", data)
    before = entries_of(root, item.id)
    try:
        set_state(root, repo_id, item.id, "filed", None, item.from_, False, item.kind, place="outbox")
    except BaseException:
        if not keep_if_appended(root, path, item.id, before, "filed"):
            rollback(root, path)
        raise
    finally:
        forget(path)
    return path


def set_state(root: Path, repo_id: str, item_id: str, state: str, note: str | None, by: str, one_way: bool,
              kind: str | None = None, extra: dict[str, Any] | None = None, place: str | None = None) -> dict[str, Any]:
    machine = machine_for(place or ("oneway" if one_way else ""), kind)
    ledger_ok(root)

    def decide(all_entries: list[dict[str, Any]]) -> tuple[str, dict[str, Any]]:
        # the predecessor is read under the ledger lock, so concurrent changes cannot both pass (review N5)
        mine = [e for e in all_entries if e.get("kind") == "state" and e.get("item") == item_id]
        now = mine[-1]["state"] if mine else None
        if state not in machine.get(now, set()):
            raise ValueError(f"{item_id}: {now or '(new)'} → {state} is not a valid transition; allowed: "
                             f"{', '.join(sorted(machine.get(now, set()))) or 'none (closed)'}")
        if state in NEEDS_NOTE and not (note or "").strip():
            raise ValueError(f"{item_id}: state {state} needs --note (a version, a reason, a target ID or evidence)")
        return "state", {"item": item_id, "state": state, "from_state": now, "note": note or "", "by": by, **(extra or {})}
    return ledger(root, repo_id).transaction(decide)


# ---------------------------------------------------------------- step 2: pull from eligible peers (0.9.0 C1)
class PeerError(ValueError):
    """The peer is not eligible for the two-way protocol; the message says why."""


def _peer_source(source: str | ExchangePeer) -> tuple[str, str, bool]:
    if isinstance(source, ExchangePeer):
        if source.url is not None:
            return source.url, source.ref, True
        assert source.path is not None
        return source.path, source.ref, "://" in source.path
    return source, "HEAD", "://" in source


def local_peer_path(root: Path, source: str | ExchangePeer) -> Path | None:
    where, _, remote = _peer_source(source)
    return None if remote else (root / Path(where).expanduser()).resolve()


def _committed_exchange(path: Path, sha: str) -> ExchangeSection:
    from .fsutil import git_run

    cfg = git_run(path, "show", f"{sha}:steward.toml", timeout=10)
    if cfg.returncode == 0:
        try:
            return ExchangeSection.model_validate(tomllib.loads(cfg.stdout.decode("utf-8")).get("exchange"))
        except (ValueError, RecursionError):
            pass
    raise PeerError("no readable [exchange] table at the selected ref")


def _checkout_head(path: Path, ref: str) -> str:
    from .fsutil import git_run

    if not path.is_dir():
        raise PeerError("the checkout folder is missing")
    top = git_run(path, "rev-parse", "--show-toplevel", text=True, timeout=10)
    if top.returncode or Path(top.stdout.rstrip("\n")).resolve() != path:
        raise PeerError("the path is not a Git checkout root")
    head = git_run(path, "rev-parse", "--verify", "--end-of-options", f"{ref}^{{commit}}", text=True, timeout=10)
    if head.returncode:
        raise PeerError("no commit at the selected ref")
    return head.stdout.strip()


@contextmanager
def peer_revision(root: Path, peer: str, source: str | ExchangePeer) -> Iterator[tuple[Path, str]]:
    """Open one committed snapshot. A URL is fetched into a temporary bare repository."""
    from tempfile import TemporaryDirectory

    from .fsutil import SAFE_GIT_CONFIG, git_env, git_run

    where, ref, remote = _peer_source(source)
    try:
        if ref != "HEAD":
            ref = ref if ref.startswith("refs/") else f"refs/heads/{ref}"
            if git_run(root, "check-ref-format", ref, timeout=10).returncode:
                raise PeerError("invalid peer ref")
        source_dir = TemporaryDirectory(prefix="steward-exchange-") if remote else nullcontext(local_peer_path(root, source))
        with source_dir as directory:
            path = Path(directory)
            if remote:
                if git_run(path, "init", "--bare", "--template=", timeout=10).returncode:
                    raise PeerError("could not prepare a temporary Git repository")
                # Only a declared URL can enable transport. Keep custom helpers, prompts, user Git configuration,
                # repository hooks and submodules out of this fetch.
                env = git_env()
                env["GIT_ALLOW_PROTOCOL"] = "file:git:http:https:ssh"
                settings = [arg for setting in SAFE_GIT_CONFIG for arg in ("-c", setting)]
                fetched = subprocess.run(
                    ["git", *settings, "-c", "core.sshCommand=ssh -oBatchMode=yes", "fetch",
                     "--depth=1", "--no-tags", "--no-recurse-submodules", "--", where, ref],
                    cwd=path, env=env, capture_output=True, timeout=30,
                )
                if fetched.returncode:
                    raise PeerError("could not fetch the selected ref")
                sha = git_run(path, "rev-parse", "--verify", "FETCH_HEAD^{commit}", text=True, timeout=10).stdout.strip()
                if not sha:
                    raise PeerError("the fetched ref does not name a commit")
            else:
                sha = _checkout_head(path, ref)
            if _committed_exchange(path, sha).code != peer:
                raise PeerError("the selected ref declares a different exchange code")
            if git_run(path, "cat-file", "-t", f"{sha}:{FOLDER}/outbox", timeout=10).stdout != b"tree\n":
                raise PeerError("no exchange/outbox folder at the selected ref")
            yield path, sha
    except PeerError as e:
        raise PeerError(f"{peer}: {e}") from None
    except (OSError, subprocess.TimeoutExpired, RuntimeError, ValueError):
        raise PeerError(f"{peer}: could not read the selected ref") from None


