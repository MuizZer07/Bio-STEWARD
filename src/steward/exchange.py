HEX64 = re.compile(r"^[0-9a-f]{64}$")


def receipt_sha(entries: list[dict[str, Any]]) -> str | None:
    """The sha256 recorded when the item was received, or None (an item received before 0.9.0, or never received)."""
    rec = entries[0].get("received") if entries and entries[0].get("state") == "acknowledged" else None
    sha = rec.get("sha256") if isinstance(rec, dict) else None
    return sha if isinstance(sha, str) and HEX64.fullmatch(sha) else None  # AB6: no trailing newline


def retired_receipt(item_id: str, entries: list[dict[str, Any]]) -> bool:
    """FB-018, AB5 – AB9 (0.18.0): the one criterion by which a received item's file may be gone. Its receipt
    holds the file's hash; its history ends superseded or withdrawn (or closed right after); a superseded entry names
    a replacement from the same sender. The CLI's advice, R-53, `exchange status` and a later receive all use it."""
    m = ID.match(item_id) if valid_id(item_id) else None
    if m is None or m.group(2) in ("RSP", "REL") or receipt_sha(entries) is None:  # AC6: requests, defects,
        return False                                                                # feedback and questions only
    done = [e.get("state") for e in entries]
    at = len(done) - 1 if done[-1] in RETIRED_STATES else \
        len(done) - 2 if done[-1] == "closed" and len(done) > 1 and done[-2] in RETIRED_STATES else None
    if at is None:
        return False
    if done[at] == "superseded":
        by = entries[at].get("superseded_by")
        return valid_id(by) and by != item_id and by.split("-")[0] == item_id.split("-")[0]
    return True


def removable(item_id: str, hist: dict[str, list[dict[str, Any]]], inbox: set[str],
              answers: dict[str, list[tuple[str, str] | None]]) -> bool:
    """Whether a received item's file may be gone (0.18.0; AB5 – AB9, AC4, AC5, AD4): the one test the command's
    advice, R-53, `exchange status`, a later receive and a close after removal all use, with the same evidence
    (`removal_context`; `inbox` holds only valid items whose file name is their ID, AD3).
    - `retired_receipt` holds for it;
    - every response this project wrote to it binds exactly the received bytes (`answers`: target -> the
      (id, sha256) binding of each response, None for one without a binding);
    - a superseded item's replacement has a hashed receipt and is valid in `inbox`, or passes this same test (a
      chain, walked iteratively, so its length is unbounded; a cycle fails)."""
    seen: set[str] = set()
    cur = item_id
    while True:
        entries = hist.get(cur, [])
        if cur in seen or not retired_receipt(cur, entries):
            return False
        seen.add(cur)
        sha = receipt_sha(entries)
        if any(a is None or a != (cur, sha) for a in answers.get(cur, [])):
            return False
        by = next((e.get("superseded_by") for e in reversed(entries) if e.get("state") == "superseded"), None)
        if by is None:
            return True
        if receipt_sha(hist.get(by, [])) is None:
            return False
        if by in inbox:
            return True
        cur = by


def valid_inbox(found: dict[str, list[tuple[str, str]]], root: Path) -> set[str]:
    """IDs of inbox files that are valid items named by their ID (strict UTF-8, as R-53 reads them; AD3)."""
    out = set()
    for rel, _ in found.get("inbox", []):
        try:
            text = (root / rel).read_bytes().decode("utf-8")
            it = Item.model_validate(parse(text)[0])
        except Exception:  # noqa: BLE001 - an unreadable or invalid file is not a present item
            continue
        if Path(rel).stem == it.id:
            out.add(it.id)
    return out


def removal_context(root: Path) -> tuple[dict[str, list[dict[str, Any]]], set[str], dict[str, list[tuple[str, str] | None]]]:
    """(ledger states, the IDs with a file in inbox/, the bindings of this project's responses by target)."""
    found = items(root)
    answers: dict[str, list[tuple[str, str] | None]] = {}
    for _, text in found.get("responses", []):
        try:
            head = parse(text)[0]
        except (ValueError, RecursionError):
            continue
        if head.get("kind") == "response" and isinstance(head.get("responds_to"), str):
            answers.setdefault(head["responds_to"], []).append(answered(text))
    return states(root), valid_inbox(found, root), answers


def may_be_gone(root: Path, item_id: str) -> bool:
    hist, inbox, answers = removal_context(root)
    return removable(item_id, hist, inbox, answers)


